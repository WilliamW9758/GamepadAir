import Foundation

public enum HIDReport {
    public static let byteCount = 13
    /// Generic gamepad: 10 buttons, null-state hat, X/Y/Rx/Ry, Z/Rz triggers.
    /// Local experimental identity; does not claim to be Sony or Microsoft hardware.
    public static let descriptor = Data([
        0x05, 0x01, 0x09, 0x05, 0xA1, 0x01,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x0A, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x0A, 0x81, 0x02,
        0x75, 0x01, 0x95, 0x06, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x39, 0x15, 0x00, 0x25, 0x07,
        0x35, 0x00, 0x46, 0x3B, 0x01, 0x65, 0x14,
        0x75, 0x04, 0x95, 0x01, 0x81, 0x42,
        0x75, 0x04, 0x95, 0x01, 0x81, 0x03,
        0x65, 0x00, 0x35, 0x00, 0x45, 0x00,
        0x09, 0x30, 0x09, 0x31, 0x09, 0x33, 0x09, 0x34,
        0x16, 0x01, 0x80, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x04, 0x81, 0x02,
        0x09, 0x32, 0x09, 0x35, 0x15, 0x00, 0x26, 0xFF, 0x00,
        0x75, 0x08, 0x95, 0x02, 0x81, 0x02, 0xC0
    ])
    public static func encode(_ state: GamepadState) -> Data {
        let wire = Array(StateFrame(sequence: 0, state: state).encode())
        return Data(Array(wire[12..<15]) + Array(wire[16..<26]))
    }
}
