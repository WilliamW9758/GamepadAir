import Foundation

/// Xbox wireless HID framing used by Unity's macOS Xbox decoder.
/// Transport from the phone is independent of the emulated controller protocol.
public enum XboxHIDReport {
    public static let byteCount = 18
    public static let descriptor = Data([
        0x05,0x01,0x09,0x05,0xA1,0x01,0x85,0x01,
        0x09,0x30,0x09,0x31,0x09,0x32,0x09,0x35,
        0x15,0x00,0x27,0xFF,0xFF,0x00,0x00,0x75,0x10,0x95,0x04,0x81,0x02,
        0x09,0x33,0x09,0x34,0x26,0xFF,0x03,0x95,0x02,0x81,0x02,
        0x09,0x39,0x15,0x01,0x25,0x08,0x35,0x00,0x46,0x3B,0x01,
        0x65,0x14,0x75,0x04,0x95,0x01,0x81,0x42,
        0x75,0x04,0x95,0x01,0x81,0x03,0x65,0x00,
        0x05,0x09,0x19,0x01,0x29,0x11,0x15,0x00,0x25,0x01,
        0x75,0x01,0x95,0x11,0x81,0x02,0x95,0x0F,0x81,0x03,
        0x06,0x00,0xFF,0x85,0x03,0x09,0x01,0x15,0x00,0x26,0xFF,0x00,
        0x75,0x08,0x95,0x08,0x91,0x02,0xC0
    ])
    public static func encode(_ state: GamepadState) -> Data {
        var bytes = [UInt8](repeating: 0, count: byteCount)
        func put(_ value: UInt16, at index: Int) {
            bytes[index] = UInt8(truncatingIfNeeded: value)
            bytes[index + 1] = UInt8(truncatingIfNeeded: value >> 8)
        }
        bytes[0] = 1
        for (index, value) in [(1,state.leftX),(3,state.leftY),(5,state.rightX),(7,state.rightY)] {
            put(UInt16(clamping: Int(value) + 32767), at: index)
        }
        put(UInt16((Int(state.leftTrigger) * 1023 + 127) / 255), at: 9)
        put(UInt16((Int(state.rightTrigger) * 1023 + 127) / 255), at: 11)
        bytes[13] = state.hat < 8 ? state.hat + 1 : 0
        for (button,bit) in [(PadButton.south,0),(.east,1),(.west,3),(.north,4),
                             (.leftShoulder,6),(.rightShoulder,7),(.back,10),(.start,11),
                             (.leftClick,13),(.rightClick,14),(.guide,12)] {
            if state.buttons & button.mask != 0 { bytes[14 + bit / 8] |= 1 << (bit % 8) }
        }
        return Data(bytes)
    }
}
